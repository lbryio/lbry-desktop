#!/usr/bin/env node
// Audits which lbrynet JSON-RPC methods the app calls (#681, part of the Go core epic #689).
//
//   node scripts/audit-rpc-methods.js > docs/go-core/rpc-methods.md
//
// A "call" is `Lbry.<name>(` or `lbryProxy.<name>(` in ui/, extras/ or electron/ (tests excluded),
// plus the names assigned to `method` where code calls `Lbry[method](...)`.
// Methods listed in ui/lbry.ts are typed wrappers; anything else goes through the Proxy fallback
// and is sent to the daemon under its own name. Plain text scan, no dependencies.

const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const SCAN_DIRS = ["ui", "extras", "electron"];
const LBRY_TS = path.join("ui", "lbry.ts");

// Members of the Lbry object that are client-side helpers, not daemon methods.
const HELPERS = new Set([
  "connect",
  "getMediaType",
  "getApiRequestHeaders",
  "setApiHeader",
  "unsetApiHeader",
  "setDaemonConnectionString",
  "setOverride",
]);

function walk(dir, out = []) {
  for (const entry of fs.readdirSync(path.join(ROOT, dir), { withFileTypes: true })) {
    const rel = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (entry.name === "node_modules" || entry.name === "__tests__") continue;
      walk(rel, out);
    } else if (/\.(ts|tsx)$/.test(entry.name)) {
      out.push(rel);
    }
  }
  return out;
}

// Methods with a typed wrapper in ui/lbry.ts: `name: (...) => daemonCallWithResult("name", ...)`.
const lbrySource = fs.readFileSync(path.join(ROOT, LBRY_TS), "utf8");
const wrapped = new Set();
for (const m of lbrySource.matchAll(/daemonCallWithResult\("([a-z_]+)"/g)) wrapped.add(m[1]);
// `publish` has its own wrapper (it supports an override) but still calls the daemon.
if (/\bpublish:\s*\(/.test(lbrySource)) wrapped.add("publish");

const calls = new Map(); // method -> ["file:line", ...]
const callRe = /\b(?:Lbry|lbryProxy)\.([A-Za-z_]+)\(/g;
for (const file of SCAN_DIRS.flatMap((d) => walk(d))) {
  if (file === LBRY_TS) continue;
  fs.readFileSync(path.join(ROOT, file), "utf8")
    .split("\n")
    .forEach((line, i) => {
      for (const m of line.matchAll(callRe)) {
        if (HELPERS.has(m[1])) continue;
        if (!calls.has(m[1])) calls.set(m[1], []);
        calls.get(m[1]).push(`${file}:${i + 1}`);
      }
    });
}

// Dynamic calls: `Lbry[method](...)`. In files that do this, treat every snake_case string
// assigned to `method` as a call (e.g. `method = x ? "channel_abandon" : "stream_abandon"`).
for (const file of SCAN_DIRS.flatMap((d) => walk(d))) {
  const text = fs.readFileSync(path.join(ROOT, file), "utf8");
  if (file === LBRY_TS || !/\b(?:Lbry|lbryProxy)\[/.test(text)) continue;
  text.split("\n").forEach((line, i) => {
    if (!/\bmethod\s*=/.test(line)) return;
    for (const m of line.matchAll(/"([a-z]+_[a-z_]+)"/g)) {
      if (!calls.has(m[1])) calls.set(m[1], []);
      calls.get(m[1]).push(`${file}:${i + 1}`);
    }
  });
}

const called = [...calls.keys()].sort();
const proxyOnly = called.filter((n) => !wrapped.has(n));
const wrappedUncalled = [...wrapped].filter((n) => !calls.has(n)).sort();

const lines = [];
lines.push("# Daemon JSON-RPC methods the UI calls", "");
lines.push(
  "Generated by `node scripts/audit-rpc-methods.js`. Do not edit by hand; re-run the script.",
  "",
  `- **${called.length}** distinct methods are called from \`ui/\`, \`extras/\` or \`electron/\`.`,
  `- **${wrapped.size}** have a typed wrapper in \`${LBRY_TS.replace(/\\/g, "/")}\`; **${proxyOnly.length}** go through the Proxy fallback only.`,
  `- **${wrappedUncalled.length}** have a wrapper but no call site.`,
  ""
);
lines.push("## Called methods", "", "| Method | Call sites | Wrapper in lbry.ts | Example call site |", "|---|---|---|---|");
for (const name of called) {
  const sites = calls.get(name);
  lines.push(`| \`${name}\` | ${sites.length} | ${wrapped.has(name) ? "yes" : "no (proxy)"} | \`${sites[0]}\` |`);
}
lines.push("", "## Wrapped but never called", "");
lines.push(
  "Safe to leave out of the first Go shim (the shim still forwards unknown methods to `lbrynet`).",
  "",
  wrappedUncalled.map((n) => `- \`${n}\``).join("\n"),
  ""
);
process.stdout.write(lines.join("\n"));
